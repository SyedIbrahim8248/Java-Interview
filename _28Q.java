public class _28Q {
    public static void main(String[] args) {
        // count positive numbers
        int[] arr = {10, -5, 20, -2, 30,3,4};
        int count = 0;

        for (int i = 0; i < arr.length; i++) {
            if (arr[i] > 0) {
                count++;
            }
        }

        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        
        System.out.println(count);
    }
}
